MARKERS = {
    "assume": re.compile(r"\bassume\s*\("),
    "admit": re.compile(r"\badmit\s*\("),
    "external_body": re.compile(r"verifier::external_body"),
    "external": re.compile(r"verifier::external\b(?!_)"),
    "assume_specification": re.compile(r"\bassume_specification\b"),
    "unsafe": re.compile(r"\bunsafe\s*(\{|fn\b|impl\b)"),
}
RESULT_RE = re.compile(r"verification results::\s*(\d+) verified,\s*(\d+) errors")
TEST_RE = re.compile(r"test result: \w+\. (\d+) passed; (\d+) failed")
VURL_WPT_IPV4_RE = re.compile(r"WPT IPv4 host cases checked:\s*(\d+)")
VURL_WPT_IPV6_RE = re.compile(r"WPT IPv6 host cases checked:\s*(\d+)")
VURL_DIFF_IPV6_RE = re.compile(r"differential:\s*(\d+)\s+parsed,\s*(\d+)\s+failures")
VURL_DIFF_IPV4_RE = re.compile(r"differential:\s*(\d+)\s+ipv4,\s*(\d+)\s+failures,\s*(\d+)\s+non-ipv4")


def stack_env() -> dict[str, str]:
    env_file = Path(os.environ.get("VERUS_STACK", Path.home() / "workspaces/verus-stack")) / "env.zsh"
    out = subprocess.run(
        ["zsh", "-c", f"source {env_file} >/dev/null && env -0"],
        capture_output=True,
        check=True,
    ).stdout.decode()
    return dict(kv.split("=", 1) for kv in out.split("\0") if "=" in kv)


def run(cmd: list[str], env: dict[str, str], cwd: Path = ROOT) -> tuple[int, str, float]:
    t0 = time.monotonic()
    p = subprocess.run(cmd, cwd=cwd, env=env, capture_output=True, text=True)
    return p.returncode, p.stdout + p.stderr, round(time.monotonic() - t0, 2)


def sanitize_home(text: str) -> str:
    return text.replace(str(Path.home()), "~")


def write_log(filename: str, blocks: list[tuple[list[str], Path, int, float, str]]) -> str:
    LOGS.mkdir(parents=True, exist_ok=True)
    chunks = []
    for cmd, cwd, code, secs, text in blocks:
        chunks.append(
            f"$ {' '.join(cmd)}\n# cwd: {cwd}\n# exit: {code}  seconds: {secs}\n\n{text.rstrip()}\n"
        )
    (LOGS / filename).write_text(sanitize_home("\n".join(chunks)))
    return f"data/logs/{filename}"


def load_fresh_json(path: Path) -> dict:
    if not path.exists():
        raise RuntimeError(f"Expected test-generated report missing after cargo test: {path}")
    return json.loads(path.read_text())


